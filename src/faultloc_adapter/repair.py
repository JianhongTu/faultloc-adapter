"""Generate Harbor *repair* tasks from the same frozen manifests.

Separate task family from the localization adapter: nothing here changes
adapter.py, prompt.md, score.py, or the vendored scorer. The two share the
manifests, the ARVO images, the agent image, and the split agent/sidecar shape.

The question a repair task measures is whether the *quality* of an external
root-cause report changes a fixed implementation agent's chance of a verified
fix. One protocol, one dataset per REPORT SOURCE:

  * `gold` -- developer-derived locations plus an annotated cause.
  * `diagnosis-<model-id>` -- that localization model's own spans and summary.

These are a set, not a pair. `gold` is the ceiling: its locations come from the
developer patch, so an agent that fixes where the developer fixed scores
attributable almost by construction, and every diagnosis dataset is read against
it. There is no fixed number of members -- each localization model evaluated adds
one more, produced at its own time from its own reports, and none of them depends
on any other existing.

Each source is therefore an independent Harbor task set, generated by its own
invocation and run as its own job. Tasks are named for the instance alone
(`repair__<local_id>`); the dataset directory carries the source. Every member
gets identical tools, budget and prompt, so a member differs from `gold` only in
the report section -- which is what scripts/repair_boundaries.py asserts, once
per candidate dataset against `gold` as the reference.

The agent gets ONE attempt and no build tool. Fix probability is measured over
repeated rollouts (`n_attempts`) and verified afterwards, which keeps the
measurement on whether the agent understood the defect rather than on how long it
was willing to iterate against a pass/fail oracle.

See README.md for the shared design constraints; sidecar/server.py for the
endpoints and why the build tree is synced rather than shared.
"""

