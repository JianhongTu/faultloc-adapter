BASELINE_TAG = "harbor-baseline"

# What makes /compile verifier-only.
#
# The agent must not build. Withholding is structural everywhere else in this
# design -- the resource is not in its container -- but /compile cannot be: the
# agent needs `poc` allowlisted to run the reproducer, Harbor's allowlist is
# host-based and rejects ports outright ("not URLs, ports, or paths"), and both
# endpoints live on the one sidecar. A POST from the agent container reached
# /compile and started a real build.
#
# So the gate is a token the agent cannot have YET. Harbor uploads `tests/` inside
# verify() (harbor/verifier/verifier.py:147), after the agent phase has ended, so
# /tests does not exist while the agent runs. The sidecar learns the same value
# from its compose environment, which no other container can read. Structural
# again, just in time rather than in space.
#
# Derived from the instance rather than random so regeneration is byte-stable and
# repair_boundaries.py still sees gold and a diagnosis dataset as identical. The
# value is not a secret -- this file is public -- but the agent has neither the
# repo nor the file, and nothing in its prompt mentions /compile.
COMPILE_TOKEN_HEADER = "X-Compile-Token"
COMPILE_TOKEN_FILE = "compile_token"


def compile_token(local_id: int) -> str:
    return hashlib.sha256(f"faultloc-compile-{local_id}".encode()).hexdigest()

# Every source supplies a report, read from `<reports-dir>/<local_id>.json`, which
# is what makes the report's *quality* the manipulated variable rather than its
# presence. No report is derivable from the manifest, so a missing file is an
# error rather than a default: falling back would not degrade the source, it
# would silently REPLACE it with the no-cause null condition while `task.toml`
# still names the original -- and that null condition measured 0/5 patch_present,
# so it would read as a real effect.
GOLD_SOURCE = "gold"

# A source is `gold` or `diagnosis-<served model id>`. Constrained rather than
# free-form because the source becomes a directory name, a task.toml field and the
# label every reward file is aggregated under: a typo would silently start a
# second dataset instead of extending one, and a bare model id with no
# `diagnosis-` prefix would read as if the model had done the repair.
#
# Derive the id from what actually answered -- the `model` field of a completion
# response, lowercased with the org prefix dropped -- not from a gateway alias,
# which can be repointed at a different checkpoint without notice.
# `Qwen/Qwen3.6-27B` -> `diagnosis-qwen3.6-27b`.
_SOURCE_PATTERN = re.compile(r"^(gold|diagnosis-[a-z0-9][a-z0-9._-]*)$")


def dataset_name(source: str) -> str:
    """Dataset directory name for a report source."""
    return f"flbench-repair-{INSTANCE_SET}-{source}"


def _producer(source: str) -> str:
    """Where a missing report was supposed to come from.

    Source-specific on purpose: one generic "see scripts/annotate_cause.py" sends
    someone missing a diagnosis report to a script that calls gold_report(), which
    would fill it with developer-patch locations and a cause written from the
    developer patch. That generates cleanly, labels itself with the diagnosis
    model's name, and runs gold against gold.
    """
    if source == GOLD_SOURCE:
        return "Generate it with scripts/annotate_cause.py --out <reports-dir>."
    return (
        "This dataset carries a localization model's OWN predictions: export them "
        "from that stage-1 run's prediction.json. Do NOT generate them with "
        "scripts/annotate_cause.py -- that writes developer-patch locations and "
        "would make this dataset a second `gold` under another name."
    )


def _runs(lines: list[int]) -> list[tuple[int, int]]:
    """Split sorted line numbers into (start, end-exclusive) contiguous runs."""
    runs: list[tuple[int, int]] = []
    for line in lines:
        if runs and line == runs[-1][1]:
            runs[-1] = (runs[-1][0], line + 1)
        else:
            runs.append((line, line + 1))
    return runs


def gold_report(manifest: dict) -> dict:
    """Root-cause report derived from the developer patch, one location per edit.

    Deliberately carries locations only. A `cause` written by summarizing the
    patch would leak the fix, so authored explanations arrive out of band via
    --reports and are the author's responsibility to keep fix-free.

    One location per CONTIGUOUS RUN, not per hunk. A hunk is a `@@` block, and git
    merges edits into one block whenever they are within a few context lines of
    each other, so `hunk.lines` is a set with gaps far more often than not --
    221 of the shipped set's hunks, over 116 of its 500 instances. Spanning
    lines[0]..lines[-1] treated that set as a range and claimed every untouched
    line between the extremes: 5507 reported lines against 4263 real ones, worst
    case 13 real lines reported as a 76-line window. That fed the agent's prompt
    and, through report_spans(), the verifier's `at_location` -- so gold, the
    ceiling every other source is read against, was scored on a wider target than
    a source that reports tightly.
    """
    locations = []
    for hunk in parse_diff_anchored(manifest["gt_diff"]):
        for start, end in _runs(sorted(hunk.lines)):
            locations.append(
                {
                    "file": hunk.file,
                    "line_start": start,
                    # Exclusive, matching the FL span convention.
                    "line_end": end,
                }
            )
    return {
        "report_id": f"gold-{manifest['local_id']}",
        "instance_id": manifest["local_id"],
        "locations": locations,
        "cause": "",
    }


def _validate_report(report: dict, path: Path, local_id: int, source: str) -> None:
    """Reject a report that would generate a different dataset than its label claims.

    Datasets differ ONLY in report content, so every field that content is made of
    has to be present. The dangerous case is a report that is merely incomplete
    rather than broken: `_render_report` used to drop the cause whenever it was
    empty, so a report with `cause: ""` rendered as locations only -- the retired
    null condition -- while task.toml still named its source. That generates
    cleanly, passes the boundary gate (the dataset still differs from gold outside
    the report by nothing, and the report sections still differ), and shows up only
    as an unexplained drop in whichever dataset was silently relabelled.

    Spans are checked structurally too: report_spans() copies them straight into
    tests/report_spans.json, where the verifier turns them into Span objects. A
    missing or non-integer bound raises there instead -- inside the container, at
    verify time, after the agent has already run.
    """
    if not str(report.get("report_id") or "").strip():
        raise ValueError(f"{path} has no report_id")
    # One report directory per source stops a dataset picking up another's
    # reports; this stops a file that was copied or renamed to the wrong id
    # rendering another instance's locations into the prompt.
    if report.get("instance_id") != local_id:
        raise ValueError(
            f"{path} is for instance {report.get('instance_id')}, not {local_id}"
        )

    locations = report.get("locations")
    if not locations:
        # `gold` locations come from the developer patch, so empty means the
        # manifest or the annotation is corrupt. Diagnosis locations come from an
        # agent that is allowed to find nothing -- a result, not corruption.
        if source == GOLD_SOURCE:
            raise ValueError(f"{path} has no locations")
        raise NoPrediction(f"stage 1 named no location ({path})")
    for i, loc in enumerate(locations):
        if not str(loc.get("file") or "").strip():
            raise ValueError(f"{path} location {i} has no file")
        start, end = loc.get("line_start"), loc.get("line_end")
        if not isinstance(start, int) or not isinstance(end, int):
            raise ValueError(
                f"{path} location {i} ({loc.get('file')}) has non-integer bounds: "
                f"line_start={start!r} line_end={end!r}"
            )
        # line_end is exclusive, so an empty or inverted span names no line at all
        # and the fix could never be attributed to it.
        if start < 1 or end <= start:
            raise ValueError(
                f"{path} location {i} ({loc.get('file')}) is not a valid span: "
                f"lines {start}-{end} (line_end is exclusive)"
            )

    if not str(report.get("cause") or "").strip():
        # Every dataset is defined by its causal explanation, so a locations-only
        # report is the null condition and must never be generated under any
        # source's name. But the sources fail differently, for the same reason as
        # the empty-locations case above: a gold report we curated with no cause is
        # a bug in our own pipeline, while a diagnosis report with spans and no
        # summary is a stage-1 result -- record it and move on rather than failing
        # the instance.
        if source == GOLD_SOURCE:
            raise ValueError(
                f"{path} has an empty cause. A curated gold report without a "
                f"causal explanation is corrupt, not a result."
            )
        raise NoPrediction(f"stage 1 wrote spans but no cause ({path})")


# Instances this dataset deliberately does not contain, and why. Written next to
# the tasks because it is part of the result: an aggregation that reads the task
# directories alone would count these instances as absent rather than as zeros,
# and silently report a diagnosis dataset over a smaller denominator than gold.
UNRUN_LEDGER = "not_run.json"


class NoPrediction(Exception):
    """A well-formed stage-1 export that yields no usable report.

    A legitimate experimental result, not an error and not a dropped instance.
    Two ways it happens: the agent named no location (the localization prompt
    permits an empty prediction -- "If you find no suspicious location, write an
    empty list" -- and an agent can also exit without writing one), or it named
    locations but no cause. Either way the repair outcome is already determined:
    a report with no line can never be the location a fix is attributed to, and
    a report with no cause is the null condition rather than this source. Every
    rollout would score at_location = 0 and therefore verified = 0.

    Generating the task would spend n_attempts rollouts of real agent budget
    rediscovering a zero derivable statically, so it is skipped. It affects this
    dataset only: sources are generated independently, and gold is not touched by
    one localization model failing on one instance.

    It is recorded as its own outcome rather than merged into the repair rate.
    "stage 1 never named a location" and "the repair agent was given a location
    and failed" are both 0, but they are different findings: the first is a
    localization result, the second a repair result, and averaging them together
    reports a repair failure that never happened. run() writes them to
    UNRUN_LEDGER for aggregation to count separately.
    """


def report_spans(report: dict) -> list[dict]:
    """The report's locations in FL span form, for the verifier."""
    return [
        {"file": loc["file"], "line_start": loc["line_start"], "line_end": loc["line_end"]}
        for loc in report["locations"]
    ]


def _render_report(report: dict) -> str:
    lines = ["## Reported Root Cause", ""]
    lines.append(
        "An external analysis identified the root cause at the following location(s). "
        "Treat it as a strong hint, not as proof; verify it against the source."
    )
    lines.append("")
    for loc in report["locations"]:
        where = f"`{loc['file']}` lines {loc['line_start']}-{loc['line_end'] - 1}"
        if loc.get("function"):
            where += f", in `{loc['function']}`"
        lines.append(f"- {where}")
    # Not conditional. Silently dropping an absent cause is what turned a
    # malformed report into the null condition under another arm's name; the
    # generator rejects that upstream, and this refuses to render it even if a
    # future caller bypasses _report().
    cause = str(report.get("cause") or "").strip()
    if not cause:
        raise ValueError(
            f"report {report.get('report_id')!r} has no cause; a locations-only "
            f"report is the null condition, not an arm"
        )
    lines += ["", f"**Cause:** {cause}"]
    return "\n".join(lines)


def _staging_command(project: str) -> str:
    """Shell run as the agent container's command, before the agent starts.

    Establishes the patch baseline. The sidecar stripped the archival .git
    (STRIP_ARCHIVAL_GIT), so the repository here is created from scratch over
    whatever it staged: the diff is against the tree the agent was actually handed
    rather than against an upstream HEAD, and the one commit in it carries no
    history the agent could read the fix out of.
    """
    return "\n".join(
        [
            "set -eu",
            "mkdir -p /workspace /logs/artifacts",
            # The staged tree was written by another container, so git refuses it
            # as dubious ownership without this.
            "git config --global --add safe.directory '*'",
            *BASELINE_REPO_STEPS,
            f"git tag {BASELINE_TAG}",
            # Same line the diagnosis `main` staging runs. The repair workspace is
            # the full-information diagnosis workspace plus a report and a
            # verifier-side build, so the reproducer is readable here too: its
            # bytes are evidence about what reaches the faulty code, and the agent
            # asked to fix the defect had less of it than the agent asked to
            # describe it.
            "curl -sf http://poc:8080/poc-file -o /workspace/poc",
            # Deliberately no compile tool. The agent gets one attempt: it reads,
            # diagnoses and edits, and the verifier builds afterwards. Fix
            # probability is then measured over repeated rollouts rather than over
            # one agent's willingness to iterate, and an agent cannot converge on
            # "the PoC stopped crashing" without understanding why.
            # Signal completion last: `docker compose up --wait` returns when the
            # container is *running*, not when this script finishes.
            f"touch {STAGED_SENTINEL}",
            "exec sleep infinity",
        ]
    )


def _instruction(manifest: dict, source: str, report: dict) -> str:
    template = (_TEMPLATE_DIR / "repair_prompt.md").read_text()
    report_section = _render_report(report)
    text = (
        template.replace("{{REPORT_SECTION}}", report_section)
        .replace("{{CRASH_TYPE}}", manifest["crash_type"] or "unknown")
        .replace("{{SANITIZER}}", manifest["sanitizer"] or "unknown")
        .replace("{{FUZZ_TARGET}}", manifest["fuzz_target"] or "unknown")
        .replace("{{SANITIZER_REPORT}}", manifest["crash_output"])
    )
    return "\n".join(line.rstrip() for line in text.splitlines()) + "\n"


class RepairAdapter:
    def __init__(
        self,
        source: str,
        limit: int | None = None,
        overwrite: bool = False,
        task_ids: list[str] | None = None,
        manifest_dir: Path | None = None,
        reports_dir: Path | None = None,
        agent_image: str = DEFAULT_AGENT_IMAGE,
        allowed_hosts: list[str] | None = None,
    ):
        self.source = source
        self.limit = limit
        self.overwrite = overwrite
        self.task_ids = task_ids
        self.manifest_dir = Path(manifest_dir or _REPO_ROOT / "manifests")
        self.reports_dir = Path(reports_dir) if reports_dir else None
        self.agent_image = agent_image
        self.allowed_hosts = list(allowed_hosts or DEFAULT_ALLOWED_HOSTS)

        if not _SOURCE_PATTERN.match(source):
            raise ValueError(
                f"invalid report source {source!r}: expected 'gold' or "
                f"'diagnosis-<model-id>' in lowercase, e.g. 'diagnosis-qwen3.6-27b'"
            )
        # Derived from the source, never caller-supplied: the only way the directory
        # name and the reports inside it cannot disagree.
        self.output_dir = DATASET_ROOT / dataset_name(source)

    def _manifests(self) -> list[dict]:
        paths = sorted(self.manifest_dir.glob("*.json"))
        if self.task_ids:
            wanted = {str(t) for t in self.task_ids}
            paths = [p for p in paths if p.stem in wanted]
            missing = wanted - {p.stem for p in paths}
            if missing:
                raise FileNotFoundError(
                    f"no manifest in {self.manifest_dir} for: {sorted(missing)}. "
                    f"Extract the shipped set with `tar -xzf data/eval500.tar.gz`."
                )
        return [manifest_mod.load(p) for p in paths]

    def _report(self, manifest: dict) -> dict:
        """The report this dataset renders, read from `<reports-dir>/<local_id>.json`.

        One report directory per source, named by the caller, so a dataset cannot
        silently pick up another source's reports. A missing file raises: see
        GOLD_SOURCE for why a fallback would quietly relabel the dataset as the
        null condition.
        """
        if not self.reports_dir:
            raise FileNotFoundError(
                f"source '{self.source}' needs authored reports; pass --reports "
                f"<dir> containing {manifest['local_id']}.json"
            )
        path = self.reports_dir / f"{manifest['local_id']}.json"
        if not path.exists():
            raise FileNotFoundError(
                f"source '{self.source}' needs an authored report for instance "
                f"{manifest['local_id']}: {path} is missing. {_producer(self.source)}"
            )
        report = json.loads(path.read_text())
        _validate_report(report, path, manifest["local_id"], self.source)
        return report

    def run(self) -> None:
        manifests = self._manifests()
        if not manifests:
            raise FileNotFoundError(f"no manifests found in {self.manifest_dir}")
        written = 0
        errors: list[tuple[int, str]] = []
        unrun: list[dict] = []
        # Instances this run actually wrote. The ledger prune keys off it: it may
        # not clear a record for a task that was already on disk when the run
        # started, only for one this run replaced.
        ran: list[int] = []
        # --limit counts INSTANCES, not tasks. Counting tasks would walk past the
        # limit for every instance that writes none -- a no-prediction export, or a
        # task already on disk -- so `--limit N` on one source and on another would
        # cover different instances, and the arms would be averaged over different
        # sets. Same reason adapter.py slices here rather than counting output.
        if self.limit is not None:
            manifests = manifests[: self.limit]
        for manifest in manifests:
            local_id = manifest["local_id"]
            try:
                if self._write_task(manifest):
                    written += 1
                    ran.append(local_id)
            except NoPrediction as e:
                # Not a failure: stage 1 produced a well-formed export with nothing
                # usable in it, which is a localization result. See NoPrediction.
                unrun.append({
                    "local_id": local_id,
                    "source": self.source,
                    "reason": "no_prediction",
                    "detail": str(e),
                    "scored_as": 0,
                })
                print(f"{local_id}: NOT RUN ({e}) -- scores 0")
            except Exception as e:
                # _write_task resolves and validates the report before it creates
                # anything, so a failure here leaves no partial task behind.
                errors.append((local_id, f"{type(e).__name__}: {e}"))
                print(f"{local_id}: FAILED {type(e).__name__}: {e}")

        self._write_unrun_ledger(unrun, ran)
        if unrun:
            print(f"\n{len(unrun)} instance(s) NOT RUN -- recorded in "
                  f"{self.output_dir / UNRUN_LEDGER}. These score 0 without a "
                  f"rollout; count them separately from instances that ran and failed.")

        if errors:
            print(f"\nwrote {written} task(s); {len(errors)} instance(s) failed "
                  f"and were left ungenerated:")
            for local_id, msg in errors:
                print(f"  {local_id}  {msg}")
            raise RuntimeError(
                f"{len(errors)} of {len(manifests)} instance(s) failed; the "
                f"dataset covers the rest. Fix the reports and re-run with "
                f"--task-ids for the failures."
            )

    def _write_unrun_ledger(self, unrun: list[dict], ran: list[int]) -> None:
        """Reconcile this dataset's ledger with what the run did, keyed by instance.

        Merged rather than overwritten because `--task-ids` runs cover a subset:
        rewriting would drop every instance recorded by an earlier partial run, and
        the ledger would under-report exactly when it is doing the most work.

        But merging alone only ever grows it. An instance recorded as not-run and
        later generated -- re-export the prediction, regenerate that instance --
        would keep its entry, and aggregation would add a phantom zero for a task
        that actually ran, biasing this dataset's rate down. The boundary gate
        cannot catch it either: the task exists, so the check takes the normal
        path. So instances written this run are pruned, and the reconcile happens
        even when nothing was skipped -- a run with no not-run instances is exactly
        the run that clears a stale entry.
        """
        path = self.output_dir / UNRUN_LEDGER
        existing = json.loads(path.read_text()) if path.exists() else []
        merged = {e["local_id"]: e for e in existing}
        for local_id in ran:
            if merged.pop(local_id, None) is not None:
                print(f"  cleared not-run record for repair__{local_id}")
        merged.update({e["local_id"]: e for e in unrun})
        if not merged:
            path.unlink(missing_ok=True)
            return
        # The ledger can be the only thing a run produces, so it cannot assume
        # _write_task already created the output directory.
        self.output_dir.mkdir(parents=True, exist_ok=True)
        path.write_text(
            json.dumps(sorted(merged.values(), key=lambda e: e["local_id"]), indent=2) + "\n"
        )

    def _write_task(self, manifest: dict) -> bool:
        task_id = f"repair__{manifest['local_id']}"
        task_dir = self.output_dir / task_id
        if task_dir.exists() and not self.overwrite:
            print(f"skip {task_id} (exists; use --overwrite)")
            return False

        # Resolve the report BEFORE touching the filesystem: _report raises when an
        # authored arm has no file, and neither outcome of doing this later is
        # acceptable. Half-built directories survive the exception, and the
        # `exists()` check above would then skip them forever, leaving a directory
        # with no task.toml posing as a generated task; and under --overwrite the
        # rmtree would already have destroyed a task that was previously fine.
        try:
            report = self._report(manifest)
        except NoPrediction:
            # The one exception that is a RESULT rather than an error: this instance
            # no longer belongs to the dataset, so a task built from an earlier
            # report must not survive. Leaving it would put the instance in the
            # dataset AND in not_run.json -- Harbor would roll out the stale task
            # while aggregation added a phantom zero for the same id, and the
            # boundary gate would see a task present and pass it.
            if task_dir.exists():
                shutil.rmtree(task_dir)
                print(f"removed {task_id} (previously generated; now not run)")
            raise

        if task_dir.exists():
            shutil.rmtree(task_dir)
        for sub in ("environment", "solution", "tests/scorer"):
            (task_dir / sub).mkdir(parents=True, exist_ok=True)

        (task_dir / "task.toml").write_text(self._task_toml(manifest, task_id, self.source))
        (task_dir / "instruction.md").write_text(_instruction(manifest, self.source, report))
        (task_dir / "environment" / "docker-compose.yaml").write_text(self._compose(manifest))

        self._write_solution(task_dir, manifest)
        self._write_tests(task_dir, manifest, self.source, report)
        print(f"wrote {task_dir}")
        return True

    def _task_toml(self, manifest: dict, task_id: str, source: str) -> str:
        hosts = ", ".join(f'"{h}"' for h in self.allowed_hosts)
        return f"""version = "1.0"

[task]
name = "flbench/{task_id}"
description = "Repair {manifest['project']}: {manifest['crash_type']} ({source})"
authors = []
keywords = ["program-repair", "security", "oss-fuzz", "arvo"]

[metadata]
difficulty = "hard"
category = "debugging"
local_id = {manifest['local_id']}
project = "{manifest['project']}"
sanitizer = "{manifest['sanitizer']}"
condition = "{source}"

[agent]
# Same as localization's: the agent reads and edits, it does not build.
timeout_sec = 1800.0
network_mode = "allowlist"
allowed_hosts = [{hosts}]

[verifier]
# The verifier compiles the agent's tree and re-runs the PoC, both through the
# sidecar, so it needs `poc` and nothing else.
timeout_sec = 2400.0
network_mode = "allowlist"
allowed_hosts = ["poc"]

[environment]
docker_image = "{self.agent_image}"
workdir = "/workspace/src"
# Staging must reach the sidecar before any agent exists; `[agent]` above is what
# policies the run itself.
network_mode = "public"
build_timeout_sec = 1800.0
cpus = 4
memory_mb = 8192
"""

    def _compose(self, manifest: dict) -> str:
        staging = _staging_command(manifest["project"]).replace("$", "$$")
        indented = "\n".join("        " + line for line in staging.splitlines())
        arvo = manifest["image"]
        project = manifest["project"]
        server = "\n".join(
            "        " + line
            for line in (_REPO_ROOT / "sidecar" / "server.py").read_text().splitlines()
        )

        return f"""# Same split as the localization task: the agent runs in `main` with no ARVO
# content of its own, and the build tree, reproducer and toolchain stay in the
# `poc` sidecar. The agent edits /workspace/src and has run_poc.sh for evidence;
# it gets no build tool. The verifier syncs that tree onto /src/{project} and
# builds it afterwards, so what compiles is exactly what the agent wrote.
services:
  main:
    init: true
    volumes:
      - "src:/workspace/src"
    healthcheck:
      test: ["CMD", "test", "-f", "{STAGED_SENTINEL}"]
      interval: 2s
      timeout: 5s
      retries: 300
      start_period: 3s
    depends_on:
      poc:
        condition: service_healthy
    command:
      - /bin/sh
      - -c
      - |
{indented}

  poc:
    init: true
    # Lets sidecar/server.py:_disable_aslr clear the randomization bit;
    # Docker's default profile denies `personality` with EPERM. Without it msan
    # instances intermittently die during sanitizer init, which a repair task
    # would silently read as "the fix did not work".
    security_opt:
      - seccomp=unconfined
    environment:
      PROJECT: "{project}"
      TIMEOUT: "{POC_TIMEOUT_SEC}"
      COMPILE_TIMEOUT: "{COMPILE_TIMEOUT_SEC}"
      # Only the verifier can present this; see COMPILE_TOKEN_HEADER. Container
      # environment, so `main` cannot read it -- it can only reach :8080.
      COMPILE_TOKEN: "{compile_token(manifest['local_id'])}"
    image: {arvo}
    networks: [default]
    volumes:
      - "src:/shared"
    command:
      - /bin/sh
      - -c
      - |
        set -eu
        cp -a /src/{project}/. /shared/
        git -C /shared clean -fdx >/dev/null
        {STRIP_ARCHIVAL_GIT}
        cat > /tmp/server.py <<'SERVER_EOF'
{server}
        SERVER_EOF
        exec python3 /tmp/server.py
    healthcheck:
      test: ["CMD", "python3", "-c",
             "import urllib.request;urllib.request.urlopen('http://localhost:8080/health')"]
      interval: 2s
      timeout: 5s
      retries: 150
      start_period: 3s

volumes:
  # tmpfs, as in the localization task: teardown keeps named volumes, so a
  # disk-backed one would leak a source tree per trial. Build output does NOT
  # land here -- it stays in the sidecar's own filesystem -- so this holds only
  # source and .git and the ceiling is not load-bearing for build size.
  src:
    driver: local
    driver_opts:
      type: tmpfs
      device: tmpfs
      o: size=4g
"""

    def _write_solution(self, task_dir: Path, manifest: dict) -> None:
        """Oracle: apply the developer patch. Never shipped to the agent."""
        solve = task_dir / "solution" / "solve.sh"
        solve.write_text(
            f"""#!/bin/bash
# Oracle: apply the frozen developer patch to the agent's working tree. The
# verifier compiles and re-runs the PoC exactly as it would for an agent, so a
# passing oracle proves the whole build/verify path, not just the scorer.
set -eu
mkdir -p /logs/artifacts
cat > /tmp/gt.diff <<'PATCH_EOF'
{manifest['gt_diff']}
PATCH_EOF
cd /workspace/src
patch -p1 < /tmp/gt.diff
echo "Applied the developer patch for {manifest['local_id']}." \\
  > /logs/artifacts/summary.txt
"""
        )
        solve.chmod(0o755)

    def _write_tests(self, task_dir: Path, manifest: dict, source: str, report: dict) -> None:
        tests = task_dir / "tests"
        for name in ("__init__.py", "types.py", "ground_truth.py", "metrics.py"):
            shutil.copy(_TEMPLATE_DIR / "scorer" / name, tests / "scorer" / name)
        shutil.copy(_TEMPLATE_DIR / "anchoring.py", tests / "anchoring.py")
        shutil.copy(_TEMPLATE_DIR / "repair_score.py", tests / "repair_score.py")
        # Always shipped: `verified` requires the fix to be attributable to the
        # reported cause, so a task with no spans could not be scored at all.
        (tests / "report_spans.json").write_text(
            json.dumps(report_spans(report), indent=2) + "\n"
        )
        # Arrives in the container only at verify time, which is the whole gate.
        (tests / COMPILE_TOKEN_FILE).write_text(
            compile_token(manifest["local_id"]) + "\n"
        )
        report_arg = "  --report-spans /tests/report_spans.json \\\n"
        test_sh = tests / "test.sh"
        # A scorer or sidecar crash deliberately leaves no reward file, so Harbor
        # errors the trial instead of recording a zero the agent did not earn.
        test_sh.write_text(
            "#!/bin/bash\n"
            "set -u\n"
            "mkdir -p /logs/verifier\n"
            "rm -f /logs/verifier/reward.json /logs/verifier/reward.txt\n"
            "python3 /tests/repair_score.py \\\n"
            "  --source /workspace/src \\\n"
            f"  --baseline {BASELINE_TAG} \\\n"
            f"  --condition {source} \\\n"
            f"{report_arg}"
            "  --artifacts /logs/artifacts \\\n"
            "  --out /logs/verifier/reward.json\n"
            "cat /logs/verifier/reward.json\n"
        )
        test_sh.chmod(0o755)
